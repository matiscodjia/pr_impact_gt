#!/usr/bin/env python3
"""Write configs/generated_q3_config.yaml: the study configuration reduced to the Q3 models.

Q3 = "does a network learn a systematic annotation bias?". M3 is trained on Dataset103
(labels = GT- drift mu = -0.5, one frozen realisation per case), M4 on Dataset104
(mu = +0.5); tier B in experiment_config.yaml.

Why a separate file (like make_seed_config.py): collect_metrics scores EVERY model of the
configuration. With experiment_config.yaml, each results_seeds/M3_... or M4_... folder would
also rescore M0-M2 (1020 rows, 1-2 h of CPU on the node, while the augmentation workers need
it). M0 is already scored (results/metrics.csv) against the same references, and the Q3
analysis combines the two.

    python cluster/make_q3_config.py
"""
import argparse
import os

import yaml

Q3_MODELS = ("M3_Drift_muMinus", "M4_Drift_muPlus")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", default="configs/experiment_config.yaml")
    ap.add_argument("--out", default="configs/generated_q3_config.yaml")
    args = ap.parse_args()
    with open(args.base, encoding="utf-8") as f:
        cfg = yaml.safe_load(f)
    models = [m for m in cfg["experiment"]["models"] if m["name"] in Q3_MODELS]
    if len(models) != len(Q3_MODELS):
        raise SystemExit(f"{args.base}: expected the Q3 models {Q3_MODELS}, found {[m['name'] for m in models]}")
    cfg["experiment"]["models"] = models
    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("# GENERATED by cluster/make_q3_config.py -- do not edit\n")
        yaml.safe_dump(cfg, f, sort_keys=False, allow_unicode=True)
    desc = ", ".join("{} (d{}, tier {})".format(m["name"], m["dataset_id"], m["tier"]) for m in models)
    print(f"{args.out}: {desc}")


if __name__ == "__main__":
    main()
