#!/usr/bin/env python3
"""Write configs/generated_seeds_config.yaml: the study configuration where the model
matrix is replaced by the seed replicates (M0/M1/M2 x seeds 1 and 2, Dataset100).

Why a separate file: experiment_config.yaml is read by report.py and collect_metrics.py for
the study; adding models to it would change the study's tables. All the other blocks
(training, scenarios, calibration, ...) are copied unchanged.

Tiers: S = seed 1, T = seed 2. Model names: M0_Star_s1, M1_Omission_s1, ...

    python cluster/make_seed_config.py
"""
import argparse
import os

import yaml

REPLICATES = [  # (base model name, base trainer)
    ("M0_Star", "nnUNetTrainerStd"),
    ("M1_Omission", "nnUNetTrainerDegradedOmissionOnly"),
    ("M2_Drift_mu0", "nnUNetTrainerDriftMu0"),
]
TIER_OF_SEED = {1: "S", 2: "T"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", default="configs/experiment_config.yaml")
    ap.add_argument("--out", default="configs/generated_seeds_config.yaml")
    args = ap.parse_args()
    with open(args.base, encoding="utf-8") as f:
        cfg = yaml.safe_load(f)
    models = []
    for seed, tier in TIER_OF_SEED.items():
        for name, trainer in REPLICATES:
            models.append({"name": f"{name}_s{seed}", "trainer": f"{trainer}_s{seed}",
                           "dataset_id": 100, "tier": tier})
    cfg["experiment"]["models"] = models
    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("# GENERATED by cluster/make_seed_config.py -- do not edit\n")
        yaml.safe_dump(cfg, f, sort_keys=False, allow_unicode=True)
    print(f"{args.out}: {len(models)} models ({', '.join(m['name'] for m in models)})")


if __name__ == "__main__":
    main()
